//! Stable domain contracts shared by Branchcraft's backend modules.

use serde::{Deserialize, Serialize};
use std::path::PathBuf;
use thiserror::Error;

/// A stable identifier for an opened repository.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(transparent)]
pub struct RepositoryId(pub String);

/// The currently checked-out branch or detached commit.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BranchInfo {
    pub display_name: String,
    pub detached: bool,
    pub unborn: bool,
}

/// A change kind on one side of the index.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum ChangeKind {
    Added,
    Modified,
    Deleted,
    Renamed,
    TypeChanged,
    Untracked,
}

/// Status for one path, preserving index and worktree state independently.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct FileStatus {
    pub path: String,
    pub previous_path: Option<String>,
    pub staged: Option<ChangeKind>,
    pub unstaged: Option<ChangeKind>,
    pub conflicted: bool,
}

/// Everything needed to render the Milestone 1 repository workspace.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RepositorySnapshot {
    pub id: RepositoryId,
    pub name: String,
    pub path: PathBuf,
    pub branch: BranchInfo,
    pub files: Vec<FileStatus>,
}

/// The repository-level classification of a changed file.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum DiffFileKind {
    Added,
    Modified,
    Deleted,
    Renamed,
    TypeChanged,
    Conflicted,
}

/// Whether a file pair is safe and useful to render as source text.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum DiffPreviewStatus {
    Ready,
    Binary,
    TooLarge,
    Unsupported,
}

/// File metadata and optional source content used by a diff renderer.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DiffFile {
    pub path: String,
    pub previous_path: Option<String>,
    pub kind: DiffFileKind,
    pub preview_status: DiffPreviewStatus,
    pub old_content: Option<String>,
    pub new_content: Option<String>,
    pub old_size: u64,
    pub new_size: u64,
}

/// The semantic kind of one line emitted by libgit2.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum DiffLineKind {
    Context,
    Added,
    Deleted,
    NoNewline,
}

/// One structured line within a diff hunk.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DiffLine {
    pub kind: DiffLineKind,
    pub old_line_number: Option<u32>,
    pub new_line_number: Option<u32>,
    pub content: String,
}

/// A contiguous changed region generated by libgit2.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DiffHunk {
    pub header: String,
    pub old_start: u32,
    pub old_lines: u32,
    pub new_start: u32,
    pub new_lines: u32,
    pub lines: Vec<DiffLine>,
}

/// A complete, bounded file diff returned to the frontend.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Diff {
    pub file: DiffFile,
    pub hunks: Vec<DiffHunk>,
}

/// Metadata returned after Branchcraft creates a local commit.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct CommitInfo {
    pub id: String,
    pub short_id: String,
    pub summary: String,
}

/// The new commit together with the repository state that follows it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct CommitResult {
    pub commit: CommitInfo,
    pub repository: RepositorySnapshot,
}

/// One commit shown in the local repository history.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct HistoryCommit {
    pub id: String,
    pub short_id: String,
    pub summary: String,
    pub description: Option<String>,
    pub author_name: String,
    pub author_email: String,
    pub authored_at: i64,
    pub author_offset_minutes: i32,
    pub parent_ids: Vec<String>,
}

/// A bounded page of commits reachable from the current `HEAD`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct CommitHistory {
    pub commits: Vec<HistoryCommit>,
    pub truncated: bool,
}

/// Whether a branch is local or a remote-tracking reference.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum BranchKind {
    Local,
    Remote,
}

/// A branch reference suitable for presentation in the branch picker.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BranchSummary {
    pub name: String,
    pub kind: BranchKind,
    pub current: bool,
    pub target: String,
    pub short_target: String,
    pub upstream: Option<String>,
}

/// Repository and branch state returned after a branch mutation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BranchOperationResult {
    pub repository: RepositorySnapshot,
    pub branches: Vec<BranchSummary>,
}

/// Transport category for a configured Git remote. OAuth credentials are
/// supplied only to credential-free GitHub HTTPS remotes.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum RemoteKind {
    GitHubHttps,
    Local,
    Unsupported,
}

/// Public, credential-free information about the repository's active remote.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RemoteInfo {
    pub name: String,
    pub display_url: String,
    pub kind: RemoteKind,
    pub tracking: bool,
    pub ahead: u64,
    pub behind: u64,
}

/// Network operation represented by a progress update.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum RemoteOperation {
    Fetch,
    Pull,
    Push,
}

/// Stable phase names used by the desktop progress UI.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum RemoteProgressPhase {
    Connecting,
    Transferring,
    Updating,
    Merging,
    Completed,
}

/// Bounded, non-secret progress data streamed from libgit2 to the frontend.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RemoteProgress {
    pub operation: RemoteOperation,
    pub phase: RemoteProgressPhase,
    pub remote_name: String,
    pub current: u64,
    pub total: u64,
    pub bytes: u64,
}

/// Result category for a completed remote operation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum RemoteOutcome {
    Fetched,
    UpToDate,
    FastForwarded,
    Merged,
    Pushed,
}

/// Repository and remote state returned after fetch, pull, or push.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RemoteOperationResult {
    pub repository: RepositorySnapshot,
    pub remote: RemoteInfo,
    pub outcome: RemoteOutcome,
}

/// Public repository metadata returned by GitHub's authenticated repository
/// listing. Clone URLs are credential-free HTTPS addresses.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GitHubRepository {
    pub id: u64,
    pub name: String,
    pub full_name: String,
    pub owner_login: String,
    pub description: Option<String>,
    pub private: bool,
    pub fork: bool,
    pub archived: bool,
    pub clone_url: String,
    pub default_branch: String,
    pub language: Option<String>,
    pub updated_at: String,
}

/// A bounded GitHub repository listing. `truncated` tells the UI when the
/// account has more repositories than Branchcraft's discovery limit.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GitHubRepositoryList {
    pub repositories: Vec<GitHubRepository>,
    pub truncated: bool,
}

/// Stable phases emitted while libgit2 clones a repository.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum CloneProgressPhase {
    Connecting,
    Receiving,
    Checkout,
    Completed,
}

/// Bounded, non-secret clone progress streamed to the frontend.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct CloneProgress {
    pub phase: CloneProgressPhase,
    pub current: u64,
    pub total: u64,
    pub bytes: u64,
}

/// User-selected application appearance. `System` follows the desktop color
/// scheme and updates when the desktop preference changes.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum ThemePreference {
    #[default]
    System,
    Light,
    Dark,
}

/// User-selected application color palette. Palettes are independent from the
/// light/dark theme so each palette can follow the selected color scheme.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum ColorPalette {
    #[default]
    Branchcraft,
    Ocean,
    Forest,
    Monochrome,
}

/// A previously opened repository stored in ordinary application settings.
/// Availability is refreshed from disk whenever settings are loaded.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RecentRepository {
    pub name: String,
    pub path: PathBuf,
    pub available: bool,
}

/// Non-secret Branchcraft preferences safe to expose to the frontend.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ApplicationSettings {
    pub theme: ThemePreference,
    pub palette: ColorPalette,
    pub recent_repositories: Vec<RecentRepository>,
}

/// Error categories for ordinary application-settings persistence.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum SettingsErrorKind {
    Read,
    Write,
    Corrupt,
    Unknown,
}

/// A safe settings error that does not expose platform paths or raw I/O
/// payloads to the frontend.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Error)]
#[error("{summary}")]
#[serde(rename_all = "camelCase")]
pub struct SettingsError {
    pub kind: SettingsErrorKind,
    pub summary: String,
    pub detail: Option<String>,
}

impl SettingsError {
    #[must_use]
    pub fn new(
        kind: SettingsErrorKind,
        summary: impl Into<String>,
        detail: Option<String>,
    ) -> Self {
        Self {
            kind,
            summary: summary.into(),
            detail,
        }
    }
}

